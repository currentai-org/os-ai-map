"""The ISO 639-3 codes the map's records use, confirmed against the Artio classification.

The allowed set for `languages`, coverage codes, pivots and lineage languages used to be SIL's
full code table, committed verbatim. SIL's terms do not allow a product to provide a means of
redistributing the code set (R-2026-11-11-p), so the full table lives on Artio only, inside
`currentai.language_representation.classification`, which holds one row per code of scope
individual or macrolanguage in the pinned code-table release. This repository keeps
`sources/snapshots/language-codes.tsv`: the codes its own records use, each confirmed to have a
row in that table, with SIL credited as the source of the identifiers. No reference names,
Part 1 or Part 2 equivalents, scopes or types are kept.

The snapshot is held to the corpus both ways. `build.validate` refuses a code the snapshot
lacks, and `tests/test_vocabulary_codes.py` refuses a snapshot code no record uses, so the file
stays the narrow table SIL allows and never grows into a copy of the code set.

Usage:
    uv run python -m build.language_codes --check   # offline: snapshot == codes in use
    uv run python -m build.language_codes --prune   # offline: drop codes no record uses
    uv run python -m build.language_codes --sync    # OSO_API_KEY: confirm new codes on Artio

A record that adds a code the snapshot lacks fails validation until `--sync` confirms the code
against Artio and writes it, which needs an OSO API key. A code with no Artio row is not an
ISO 639-3 code of scope individual or macrolanguage in the pinned release, and `--sync` refuses it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "sources" / "snapshots" / "language-codes.tsv"
TABLE = "currentai.language_representation.classification"
COLUMN = "iso639_3"

HEADER = [
    "# ISO 639-3 identifiers used by the Open Source AI Gap Map's records, and only those.",
    "# Source of the identifiers: ISO 639-3, https://iso639-3.sil.org (SIL International,",
    "# Registration Authority). This list is not part of the standard and does not reproduce the",
    "# code tables: it holds no reference names, Part 1 or Part 2 equivalents, scopes or types.",
    "# Each code is confirmed against currentai.language_representation.classification on Artio.",
    "# Generated by `uv run python -m build.language_codes`; do not edit by hand.",
]


def used_codes(root: Path = ROOT) -> dict[str, set[str]]:
    """Every ISO 639-3 code the corpus uses, mapped to the files that use it."""
    out: dict[str, set[str]] = {}

    def add(code: object, where: str) -> None:
        if isinstance(code, str):
            out.setdefault(code, set()).add(where)

    for path in sorted((root / "sources" / "products").glob("*.yaml")):
        for code in (yaml.safe_load(path.read_text()) or {}).get("languages") or []:
            add(code, f"sources/products/{path.name}")
    for path in sorted((root / "sources" / "scores").glob("*.yaml")):
        cap = (yaml.safe_load(path.read_text()) or {}).get("capability") or {}
        where = f"sources/scores/{path.name}"
        for entry in cap.get("language_coverage") or []:
            if isinstance(entry, dict):
                add(entry.get("language"), where)
                add(entry.get("source_language"), where)
        for code in cap.get("pivot_languages") or []:
            add(code, where)
    lineage = yaml.safe_load((root / "sources" / "lineage.yaml").read_text()) or {}
    for section in ("components", "relationships"):
        for rec in lineage.get(section) or []:
            for code in rec.get("languages") or []:
                add(code, "sources/lineage.yaml")
            for ov in rec.get("overrides") or []:
                for code in ov.get("languages") or []:
                    add(code, "sources/lineage.yaml")
    return out


def read_snapshot(path: Path = SNAPSHOT) -> list[str]:
    """The snapshot's codes, in file order. Comment lines and the column header are skipped."""
    lines = [line.rstrip("\r") for line in path.read_text(encoding="utf-8").split("\n")]
    rows = [line for line in lines if line.strip() and not line.startswith("#")]
    if not rows or rows[0] != COLUMN:
        raise ValueError(f"{path}: expected a {COLUMN!r} header after the comment lines")
    return rows[1:]


def write_snapshot(codes: set[str], path: Path = SNAPSHOT) -> None:
    path.write_text("\n".join(HEADER + [COLUMN] + sorted(codes)) + "\n", encoding="utf-8")


def confirm_on_artio(codes: set[str]) -> set[str]:
    """The subset of `codes` with a row in the Artio classification table."""
    from build.warehouse import query

    found: set[str] = set()
    ordered = sorted(codes)
    for i in range(0, len(ordered), 500):
        chunk = ordered[i:i + 500]
        quoted = ", ".join(f"'{c}'" for c in chunk if c.isascii() and c.isalpha() and c.islower())
        if not quoted:
            continue
        rows = query(f"SELECT {COLUMN} FROM {TABLE} WHERE {COLUMN} IN ({quoted})")
        found |= {row[COLUMN] for row in rows}
    return found


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="snapshot equals the codes in use (offline)")
    mode.add_argument("--prune", action="store_true", help="drop codes no record uses (offline)")
    mode.add_argument("--sync", action="store_true", help="confirm codes in use on Artio and write them")
    args = ap.parse_args(argv)

    used = used_codes()
    have = set(read_snapshot()) if SNAPSHOT.exists() else set()
    missing, unused = sorted(set(used) - have), sorted(have - set(used))

    if args.check:
        for code in missing:
            print(f"missing: {code} (used in {', '.join(sorted(used[code]))})")
        for code in unused:
            print(f"unused: {code}")
        print(f"{len(have)} code(s) in the snapshot, {len(used)} in use")
        return 1 if missing or unused else 0

    if args.prune:
        write_snapshot(have & set(used))
        print(f"dropped {len(unused)} unused code(s); {len(missing)} in use still need --sync")
        return 0

    confirmed = confirm_on_artio(set(missing)) if missing else set()
    refused = sorted(set(missing) - confirmed)
    write_snapshot((have & set(used)) | confirmed)
    print(f"confirmed {len(confirmed)} new code(s) on Artio, dropped {len(unused)} unused")
    for code in refused:
        print(f"refused: {code} has no row in {TABLE} (used in {', '.join(sorted(used[code]))})")
    return 1 if refused else 0


if __name__ == "__main__":
    sys.exit(main())
