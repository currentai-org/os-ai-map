"""Retire `openness.components.context.governance` from the score corpus (#684, phase 5).

## The contract this implements

**Old.** A product whose ladder does not read `governance` could record who governs it as a
keyed clause, `governance:Hugging Face` or `governance:Linux-Foundation/AAIF(...)`, under
`openness.components.context`, and mirrored in the `openness.raw` string. The clause was
recorded and never scored: no ladder declares or reads the key. It was also the only place the
corpus said who stood behind a product, and it said it in free prose, so nothing could count or
join on it.

**New.** The fact lives on identity records, as controlled values. The owning org's `country`
and `type` say where and what kind of body it is, and a product's `steward` names the governing
org when that is not the owner (docs/reference/identity.md, "Country, steward and languages";
curation record in docs/sweeps/2026-09-30-identity-attributes/). The clause is removed, and
`build/check_components.py` refuses it under `context` so it cannot come back.

**The mapping.** For every score file whose `openness.components.context` holds `governance`:

  * the `governance` entry leaves `context`; a `context` left empty is dropped, because
    `check_components` requires it to be non-empty or absent;
  * the same clause leaves `openness.raw`, with every other clause kept byte for byte, so the
    string still says what the mapping says (`check_components` compares the two).

Nothing else moves. `openness.score`, `openness.class`, the note, the sources and the other
axes are untouched, and the run asserts that per file before writing.

## Why this is its own migration

It is the one step of #684 that changes `raw`, and `raw` is what the payload publishes as the
product's components text, so the front end sees those strings change. Everything else in the
batch adds an optional field. The warehouse side follows too: `serialize_rubric` emits one
evidence row per recorded component key, context included, so a category's openness row count
falls by one per file touched. That is a static-model reload, which is a maintainer step
(docs/operations/deploy-models.md).

## How

The files to change are derived from the corpus, never listed here. Each edit goes through
`build/components.py` (`set_field` for `components` and for `raw`), which re-parses the file and
refuses to write unless only that field moved. A corpus file is never loaded and dumped.
Idempotent: a second run finds nothing to do and exits 0. `raw` is regenerated by removing the
clause from the string the file already carries, not by re-rendering the mapping, so a clause
the curator wrote with unusual spacing survives.

A record that carries `governance` at the top level of `components` (a ladder reading it, which
none does) or in `raw` only is refused with an error rather than repaired: it is a different
question, and choosing between the two is a curation call.

Usage:
    uv run python -m build.retire_governance            # dry run: the plan and the distributions
    uv run python -m build.retire_governance --write    # rewrite the files
"""

from __future__ import annotations

import argparse
import copy
import sys
from collections import Counter
from pathlib import Path

import yaml

from build.check_rubric import (
    CONTEXT,
    FREE_TEXT,
    _clauses,
    components_of,
    entries,
    recompose,
    split_components,
)
from build.components import set_field

ROOT = Path(__file__).resolve().parents[1]

KEY = "governance"


def strip_clause(raw: str, key: str = KEY) -> str:
    """`raw` without the clause keyed `key`, every other clause byte for byte.

    `_clauses` splits at paren depth zero and keeps the text of each clause as written, so
    rejoining on `;` gives back the original string wherever nothing was removed.
    """
    kept = [c for c in _clauses(raw) if c.split(":", 1)[0].strip() != key or ":" not in c]
    return ";".join(kept)


def migrate_text(text: str, key: str = KEY) -> str | None:
    """The file text with `key` retired, or None when the file does not carry it.

    Raises ValueError for a shape this migration does not cover, and on any assertion failure.
    """
    doc = yaml.safe_load(text) or {}
    openness = doc.get("openness") or {}
    components = openness.get("components")
    if not isinstance(components, dict):
        return None
    context = components.get(CONTEXT)
    in_context = isinstance(context, dict) and key in context
    raw = openness.get("raw")
    in_raw = isinstance(raw, str) and key in split_components(raw)

    if key in components:
        raise ValueError(f"`{key}` is recorded at the top level of components, not under {CONTEXT}")
    if not in_context and not in_raw:
        return None
    if in_context != in_raw:
        where = "raw" if in_raw else CONTEXT
        raise ValueError(f"`{key}` is in {where} but not in {'components' if in_raw else 'raw'}")

    new_components = copy.deepcopy(components)
    remaining = {k: v for k, v in context.items() if k != key}
    if remaining:
        new_components[CONTEXT] = remaining
    else:
        del new_components[CONTEXT]
    new_raw = strip_clause(raw, key)

    out = set_field(text, new_components)
    out = set_field(out, new_raw, key="raw")

    after = (yaml.safe_load(out) or {}).get("openness") or {}
    if recompose(after["components"]) != split_components(after["raw"]):
        raise ValueError("components and raw disagree after the edit; refusing to write")
    if components_of(after) != {k: v for k, v in components_of(openness).items() if k != key}:
        raise ValueError(f"the edit removed something other than `{key}`; refusing to write")
    if after["components"].get(FREE_TEXT) != components.get(FREE_TEXT):
        raise ValueError("free_text moved; refusing to write")
    return out


def plan(root: Path = ROOT, key: str = KEY) -> dict[Path, str]:
    """path -> new text, for every score file that carries `key`, derived from the corpus."""
    out: dict[Path, str] = {}
    for path in sorted((root / "sources" / "scores").glob("*.yaml")):
        try:
            new_text = migrate_text(path.read_text(), key)
        except ValueError as error:
            raise ValueError(f"{path.stem}: {error}") from None
        if new_text is not None:
            out[path] = new_text
    return out


def component_counts(docs: dict[str, dict]) -> Counter:
    """Score files carrying each component key (context lifted in), plus the reserved blocks."""
    counts: Counter = Counter()
    for doc in docs.values():
        components = (doc.get("openness") or {}).get("components")
        if not isinstance(components, dict):
            continue
        counts.update(list(entries(components)))
        counts.update(k for k in (FREE_TEXT, CONTEXT) if components.get(k))
    return counts


def outside_components(doc: dict) -> dict:
    """The document with `openness.components` and `openness.raw` removed."""
    rest = copy.deepcopy(doc)
    for field in ("components", "raw"):
        (rest.get("openness") or {}).pop(field, None)
    return rest


def report(root: Path, changes: dict[Path, str]) -> bool:
    """Print the before/after distributions; True when nothing outside components/raw moved."""
    before = {p.stem: yaml.safe_load(p.read_text()) or {} for p in (root / "sources" / "scores").glob("*.yaml")}
    after = {
        p.stem: yaml.safe_load(changes[p]) if p in changes else before[p.stem]
        for p in (root / "sources" / "scores").glob("*.yaml")
    }
    moved = [slug for slug in before if outside_components(before[slug]) != outside_components(after[slug])]
    changed_score = [
        slug for slug in before
        if any((before[slug].get("openness") or {}).get(f) != (after[slug].get("openness") or {}).get(f)
               for f in ("score", "class"))
    ]

    cb, ca = component_counts(before), component_counts(after)
    width = max((len(k) for k in set(cb) | set(ca)), default=10)
    print(f"{'component key':<{width}}  {'before':>6}  {'after':>6}")
    keys = sorted(set(cb) | set(ca), key=lambda k: (-cb[k], k))
    # A key carried by one file that did not change is a line of noise; count them instead.
    singles = [k for k in keys if cb[k] == ca[k] == 1]
    for k in (k for k in keys if k not in singles):
        flag = "  <-" if cb[k] != ca[k] else ""
        print(f"{k:<{width}}  {cb[k]:>6}  {ca[k]:>6}{flag}")
    print(f"({len(singles)} further keys, each on one file, unchanged)")
    print(f"distinct keys: {sum(1 for k in keys if cb[k])} before, {sum(1 for k in keys if ca[k])} after")

    for label, field in (("openness.score", "score"), ("openness.class", "class")):
        b = Counter((d.get("openness") or {}).get(field) for d in before.values())
        a = Counter((d.get("openness") or {}).get(field) for d in after.values())
        same = "identical" if a == b else "DIFFERENT"
        print(f"\n{label} distribution, before vs after: {same}")
        for v in sorted(b, key=str):
            print(f"  {v!s:<24}{b[v]:>6}{a[v]:>8}")
    print(f"\nproducts whose openness.score or openness.class changed: {len(changed_score)}")
    print(f"products with anything outside components/raw changed:   {len(moved)}")
    return not moved and not changed_score


def main(argv: list[str] | None = None, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--write", action="store_true", help="rewrite the files (default: dry run)")
    args = parser.parse_args(argv)

    try:
        changes = plan(root)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    for path in changes:
        print(f"  {path.stem}")
    verb = "rewrote" if args.write else "would rewrite"
    print(f"\n{verb} {len(changes)} score file(s): `{KEY}` out of components.context and raw\n")

    if not report(root, changes):
        print("error: the migration moved something it must not; nothing written", file=sys.stderr)
        return 1
    if args.write:
        for path, text in changes.items():
            path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
