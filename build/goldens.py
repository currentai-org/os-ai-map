"""Corpus-wide goldens, computed from sources/ and written to tests/goldens/corpus.json.

Why this exists: adding one product used to move six pinned constants across six test
files, so two PRs touching different products collided on every add. The pins now live
here, regenerated by regenerate.yml on main after canonical state changes, and never
appear in a proposal PR (generated-files-guard blocks the file). The intentional-change
gate the pins provided is build/check_corpus_diff.py, which runs on every PR.

Usage:
    uv run python -m build.goldens --write     # regenerate tests/goldens/corpus.json
    uv run python -m build.goldens --check     # exit 1 if the file is stale for this tree
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GOLDEN_PATH = Path("tests/goldens/corpus.json")

SOFTWARE_CATEGORIES = frozenset({
    "deployment", "agent_tools_protocols", "dataset_processing_tools", "evaluation_code",
    "finetuning_code", "inference_code", "ml_frameworks", "orchestration_agents", "ui_api",
    "telemetry_observability", "compilers", "storage",
})

# The same fixed test identities tests/test_axis_assessments.py and tests/test_axis_scoring_trace.py
# pin their content digests with, so a digest here moves only on a declaration or ladder change,
# never on an ordinary commit whose SHA those tests deliberately exclude. `resolve()` on each
# module derives the real, commit-scoped identity instead, which would make every digest here
# move on every commit — not what a golden is for.
TEST_DVID = "test-declaration-version"
TEST_SHA = "test-git-sha"


def fingerprint(root: Path) -> str:
    """sha256 over every file under sources/, by sorted relative path and content hash."""
    h = hashlib.sha256()
    base = root / "sources"
    for path in sorted(p for p in base.rglob("*") if p.is_file()):
        h.update(str(path.relative_to(base)).encode())
        h.update(hashlib.sha256(path.read_bytes()).hexdigest().encode())
    return h.hexdigest()


def _digest(lines: list[str]) -> str:
    return hashlib.sha256("\n".join(sorted(lines)).encode()).hexdigest()


def compute(root: Path) -> dict:
    from build import adoption_reconciliation, axis_assessments, axis_scoring_trace
    from build.check_parity import local_scores
    from build.check_rubric import check_category
    from build.sweep_status import under_coverage
    from tests.test_serialize_rubric import _real_sources, build_rubric_tables  # see step 5

    aa_rows = axis_assessments.axis_assessments(
        *axis_assessments.load_inputs(root),
        declaration_version_id=TEST_DVID, source_git_sha=TEST_SHA,
    )
    ar_rows = adoption_reconciliation.resolve_over_baseline(root, allow_dirty=True)
    trace = axis_scoring_trace.evaluate(
        *axis_scoring_trace.load_inputs(root),
        declaration_version_id=TEST_DVID, source_git_sha=TEST_SHA,
    )
    computed, deferred = local_scores(None)
    tables = build_rubric_tables(_real_sources(root))
    per_cat = lambda name: _per_category(tables[name])  # noqa: E731
    uc = sorted({slug for slug, _axis, _note in under_coverage()})

    return {
        "axis_assessments": {
            "rows": len(aa_rows),
            "digest": _digest([axis_assessments.canonical_row(r) for r in aa_rows]),
        },
        "adoption_reconciliation": {
            "rows": len(ar_rows),
            "digest": _digest([adoption_reconciliation.canonical_row(r) for r in ar_rows]),
        },
        "axis_scoring_trace": {
            table: [len(rows), _digest([axis_scoring_trace.canonical_row(table, r) for r in rows])]
            for table, rows in trace.items()
        },
        "parity": {"computed": len(computed), "deferred": len(deferred)},
        "rubric_rows": {
            "product_openness_evidence": per_cat("product_openness_evidence"),
            "category_scoring_rules": per_cat("category_scoring_rules"),
        },
        "check_rubric": {
            slug: {"reproduced": rep.reproduced, "total": rep.total}
            for slug in ("base_pretrained", "finetuned_chat")
            for rep in [check_category(slug, verbose=False)]
        },
        "under_coverage": {"count": len(uc), "slugs": uc},
    }


def _per_category(rows: list[dict]) -> dict[str, int]:
    out: dict[str, int] = {}
    for row in rows:
        out[row["category_slug"]] = out.get(row["category_slug"], 0) + 1
    return dict(sorted(out.items()))


def load(root: Path) -> dict:
    return json.loads((root / GOLDEN_PATH).read_text())


def write(root: Path) -> dict:
    data = {
        "sources_fingerprint": fingerprint(root),
        "computed_at_commit": subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=root, capture_output=True, text=True, check=True
        ).stdout.strip(),
        **compute(root),
    }
    (root / GOLDEN_PATH).parent.mkdir(parents=True, exist_ok=True)
    (root / GOLDEN_PATH).write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
    return data


def main(argv: list[str] | None = None, root: Path | None = None) -> int:
    root = root or ROOT
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.write:
        data = write(root)
        print(f"wrote {GOLDEN_PATH}: {data['axis_assessments']['rows']} axis rows, "
              f"{data['adoption_reconciliation']['rows']} assessments")
        return 0
    current = load(root)
    if current["sources_fingerprint"] != fingerprint(root):
        print(f"{GOLDEN_PATH} is stale: sources/ fingerprint differs. "
              f"Run `uv run python -m build.goldens --write` on main.")
        return 1
    fresh = compute(root)
    stale = [k for k in fresh if fresh[k] != current.get(k)]
    if stale:
        print(f"{GOLDEN_PATH} differs from a recompute with unchanged sources/: {stale}. "
              f"A producer changed. Regenerate deliberately, never to make a red test green.")
        return 1
    print(f"{GOLDEN_PATH} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
